import { expect, test } from "@playwright/test";
test.beforeEach(async ({ page }) => { await page.goto("/"); await page.evaluate(() => localStorage.clear()); await page.reload(); });
test("custom bouquet keeps exact recipe through checkout, admin and cancellation", async ({ page }) => {
  await page.getByRole("button", { name: "دسته‌گل دلخواه", exact: true }).click();
  await expect(page.getByRole("button", { name: "افزودن دسته‌گل دلخواه به سبد", exact: false })).toBeDisabled();
  await expect(page.getByRole("button", { name: "افزودن بسته لاله سفید", exact: true })).toBeDisabled();
  await page.getByRole("button", { name: "افزودن بسته داوودی سفید", exact: true }).click();
  await page.getByRole("button", { name: "افزودن بسته رز قرمز", exact: true }).click();
  await expect(page.locator(".stem-count")).toContainText("۱۹ تا ۲۰");
  await expect(page.locator(".summary-total")).toContainText("۱٬۸۹۰٬۰۰۰");
  await page.getByRole("radio", { name: "کاغذ صورتی", exact: false }).click();
  await page.getByRole("radio", { name: "گرد و کلاسیک", exact: true }).click();
  await expect(page.locator(".summary-total")).toContainText("۱٬۹۲۰٬۰۰۰");
  await page.getByRole("button", { name: "افزودن دسته‌گل دلخواه به سبد", exact: false }).click();
  await page.getByRole("button", { name: "دیدن سبد خرید", exact: false }).click();
  await expect(page.locator(".composition-details")).toContainText("۱ بسته داوودی سفید");
  await expect(page.locator(".composition-details")).toContainText("۱ بسته رز قرمز");
  await page.locator(".date-options button").nth(3).click();
  await page.getByRole("button", { name: "ورود نمونه برای ادامه خرید", exact: true }).click();
  await page.getByRole("button", { name: "شبیه‌سازی ورود موفق", exact: false }).click();
  await page.getByRole("button", { name: "سبد خرید", exact: true }).click();
  await page.getByRole("button", { name: "شبیه‌سازی پرداخت موفق زرین‌پال", exact: true }).click();
  await expect(page.locator(".order-card .composition-details")).toContainText("گرد و کلاسیک");
  await page.getByRole("button", { name: "دیدن داشبورد مدیریت", exact: false }).click();
  await expect(page.locator(".admin-order .composition-details")).toContainText("۱۵ شاخه");
  await page.getByRole("button", { name: "محصولات", exact: true }).click();
  const daisy = page.locator(".pack-admin > div").filter({ hasText: "داوودی سفید" });
  await expect(daisy.locator(".quantity")).toContainText("۷ بسته");
  await page.getByRole("button", { name: "پیگیری سفارش", exact: true }).first().click();
  await page.getByRole("button", { name: "لغو سفارش", exact: true }).click();
  await page.getByRole("button", { name: "تأیید لغو نمایشی", exact: true }).click();
  await page.getByRole("button", { name: "دیدن داشبورد مدیریت", exact: false }).click();
  await page.getByRole("button", { name: "محصولات", exact: true }).click();
  await expect(daisy.locator(".quantity")).toContainText("۸ بسته");
});
test("navigation has separate pages and browser back works", async ({ page }) => {
  await page.getByRole("button", { name: "گل‌های مارلو", exact: true }).click();
  await expect(page.locator(".product-card")).toHaveCount(5);
  await expect(page.locator(".hero")).toHaveCount(0);
  await page.getByRole("button", { name: "دسته‌گل دلخواه", exact: true }).click();
  await expect(page.locator(".builder-page")).toBeVisible();
  await page.goBack();
  await expect(page.locator(".catalog-page")).toBeVisible();
  await page.reload();
  await expect(page.locator(".catalog-page")).toBeVisible();
});
test("builder mobile layout and cart limits", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "دسته‌گل دلخواه", exact: true }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  for (let i = 0; i < 6; i++) await page.getByRole("button", { name: "افزودن بسته رز قرمز", exact: true }).click();
  await expect(page.getByRole("button", { name: "افزودن بسته رز قرمز", exact: true })).toBeDisabled();
  await page.getByRole("button", { name: "افزودن دسته‌گل دلخواه به سبد", exact: false }).click();
  await page.getByRole("button", { name: "سبد خرید", exact: true }).click();
  await page.getByRole("button", { name: "افزایش دسته‌گل دلخواه شما", exact: true }).click();
  await expect(page.locator(".cart-item .quantity span")).toHaveText("۱");
});
